let a = 20;
let b = 10;
console.log("Equal: ",a==b);    //checks if a equals b
console.log("Strict Equal: ", a===b);   //checks if a equals b in value and datatype
console.log("Not Equal: ",a!=b);
console.log("Greater: ",a>b);
console.log("Less : ",a<b);
console.log("Greater than or equal: ",a>=b);
console.log("Less than or equal: ",a<=b);